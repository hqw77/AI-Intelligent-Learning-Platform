"""敏感词过滤 -- 内容安全的基础实现.

这个文件是干什么的:
出题前检查用户输入有没有敏感词 (黄赌毒暴恐等), 有就拒绝.

注意 (面试可提):
这是 MVP 阶段的「最简实现」-- 一个关键词列表做子串匹配.
优点是简单, 缺点是很容易绕过 (比如用谐音, 空格, 同义替换).
正式上线应该接专业的内容安全审核接口 (如阿里云/腾讯云内容安全).
"""

# MVP 阶段使用简单的关键词列表过滤
BLOCKED_KEYWORDS = [
    "暴力",
    "色情",
    "赌博",
    "毒品",
    "自杀",
    "恐怖",
    "炸弹",
    "爆炸",
    "入侵",
    "黑客攻击",
    "武器",
]


def check_content(text: str) -> bool:
    """检查文本是否包含敏感词, 返回 True 表示安全.

    实现: 把文本转小写后, 逐个敏感词做子串匹配, 命中任一即不安全.
    """
    text_lower = text.lower()
    for kw in BLOCKED_KEYWORDS:
        if kw in text_lower:
            return False
    return True
